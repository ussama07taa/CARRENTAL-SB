const {chromium}=require(process.env.PLAYWRIGHT_MODULE||'playwright');
const {expect}=require((process.env.PLAYWRIGHT_MODULE||'playwright')+'/test');
const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict');
const local=path.resolve(__dirname,'../.local');
const credentials=JSON.parse(fs.readFileSync(path.join(local,'demo-account.json'),'utf8'));
(async()=>{
 const browser=await chromium.launch({channel:'chrome',headless:true});
 try{
 const context=await browser.newContext({viewport:{width:1440,height:1000}});
 const page=await context.newPage();const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('http://localhost:3000/login');
 await page.getByLabel('Adresse e-mail',{exact:true}).fill(credentials.email);
 await page.getByLabel('Mot de passe',{exact:true}).fill(credentials.password);
 await page.getByRole('button',{name:'Se connecter',exact:true}).click();
 await expect(page).toHaveURL('http://localhost:3000/');
 await page.getByRole('link',{name:'Véhicules',exact:true}).click();
 await expect(page.getByRole('button',{name:'Ajouter un véhicule',exact:true})).toBeVisible();

 const plate='TEST-FLOW-'+Date.now().toString().slice(-9);
 await page.getByRole('button',{name:'Ajouter un véhicule',exact:true}).click();
 await page.locator('input[name=plate]').fill(plate);
 await page.locator('select[name=make_choice]').selectOption('Dacia');
 await page.locator('select[name=model_choice]').selectOption('Logan');
 await page.getByRole('button',{name:'Créer le fichier',exact:true}).click();
 await expect(page.locator('.vehicle-summary')).toBeVisible();
 await expect(page.getByText('Votre véhicule est enregistré.',{exact:true})).toBeVisible();
 await expect(page.locator('.vehicle-header')).toContainText(plate);
 await page.getByRole('button',{name:'Ajouter l’assurance et les documents ↓',exact:true}).click();
 await expect(page.locator('#v-doc-title')).toBeFocused();
 await expect(page.locator('.v-doc-columns')).toContainText('Prochaine échéance');
 const add=page.getByRole('button',{name:'Ajouter Assurance',exact:true});
 await expect(add).toHaveText('Ajouter l’assurance ↗');await add.click();
 const editor=page.locator('.v-document-dialog');
 await editor.locator('input[name=provider]').fill('Assureur fictif parcours');
 await editor.locator('input[name=effective_on]').fill('2026-10-01');
 await editor.locator('input[name=expires_on]').fill('2027-10-01');
 await editor.getByRole('button',{name:'Enregistrer la pièce',exact:true}).click();
 await expect(editor).toHaveCount(0);
 await page.getByRole('button',{name:'Joindre le document Assurance',exact:true}).click();
 await expect(editor.locator('input[name=provider]')).not.toBeVisible();
 await expect(editor.locator('textarea[name=reason]')).toHaveCount(0);
 await editor.getByRole('button',{name:'Enregistrer le document',exact:true}).click();
 await expect(editor.locator('#doc-error-file')).toHaveText('Choisissez le justificatif à joindre.');
 const png=await page.evaluate(()=>{const c=document.createElement('canvas');c.width=300;c.height=180;const x=c.getContext('2d');x.fillStyle='#fff';x.fillRect(0,0,300,180);x.fillStyle='#000';x.fillText('DOCUMENT FICTIF',20,60);return c.toDataURL('image/png').split(',')[1]});
 await editor.getByLabel('Fichier justificatif', {exact:true}).setInputFiles({name:'test.png',mimeType:'image/png',buffer:Buffer.from(png,'base64')});
 await editor.getByRole('button',{name:'Enregistrer le document',exact:true}).click();
 await expect(editor).toHaveCount(0);
 const row=page.locator('.v-doc-row').filter({has:page.locator('.v-doc-name strong',{hasText:/^Assurance$/})});
 await expect(row).toContainText('Fichier joint · version 2');
 await expect(row).toContainText('1 oct. 2027');
 await page.getByRole('button',{name:'Historique Assurance',exact:true}).click();
 await expect(row).toContainText('Ajout du justificatif sans modification des informations');
 await page.getByRole('button',{name:'Historique Assurance',exact:true}).click();
 await page.locator('.v-documents').scrollIntoViewIfNeeded();
 await page.screenshot({path:path.join(local,'documents-clear-desktop.png')});
 await page.setViewportSize({width:390,height:844});
 await page.locator('.v-documents').scrollIntoViewIfNeeded();
 await page.screenshot({path:path.join(local,'documents-clear-mobile.png')});
 assert(await page.locator('.vehicle-dialog').evaluate(el=>el.scrollWidth<=el.clientWidth+1));
 await page.getByRole('button',{name:'Fermer',exact:true}).click();
 await page.getByLabel('Rechercher un véhicule', {exact:true}).fill(plate);
 await page.getByRole('button',{name:'Ouvrir '+plate,exact:true}).click();
 await expect(page.locator('.v-created-next')).toHaveCount(0);
 await expect(page.getByRole('button',{name:'Télécharger Assurance',exact:true})).toBeVisible();
 assert.equal(errors.length,0,errors.join(' | '));
 console.log('PASS: creation opens correct vehicle, document CTA, labelled columns, attachment-only upload preserves dates/history, required file, mobile, reopen.');
 }finally{await browser.close();}
})().catch(e=>{console.error(e);process.exit(1)});
