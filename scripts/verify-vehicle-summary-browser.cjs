const {chromium}=require(process.env.PLAYWRIGHT_MODULE||'playwright');
const {expect}=require((process.env.PLAYWRIGHT_MODULE||'playwright')+'/test');
const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict');
const local=path.resolve(__dirname,'../.local');
const credentials=JSON.parse(fs.readFileSync(path.join(local,'demo-account.json'),'utf8'));
(async()=>{
 const browser=await chromium.launch({channel:'chrome',headless:true});
 try{
 const context=await browser.newContext({viewport:{width:1440,height:1000}});
 const page=await context.newPage();const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('http://localhost:3000/login');
 await page.getByLabel('Adresse e-mail',{exact:true}).fill(credentials.email);
 await page.getByLabel('Mot de passe',{exact:true}).fill(credentials.password);
 await page.getByRole('button',{name:'Se connecter',exact:true}).click();
 await expect(page).toHaveURL('http://localhost:3000/');
 await page.getByRole('link',{name:'Véhicules',exact:true}).click();
 await expect(page.getByRole('button',{name:'Ouvrir DEMO-1',exact:true})).toBeVisible();
 await page.screenshot({path:path.join(local,'vehicles-desktop.png'),fullPage:true});

 await page.getByLabel('Rechercher un véhicule', {exact:true}).fill('TEST-UI-01');
 const open=page.getByRole('button',{name:'Ouvrir TEST-UI-01',exact:true});
 await open.click();
 await expect(page.locator('.vehicle-summary')).toBeVisible();
 await expect(page.locator('input[name=plate]')).toHaveCount(0);
 await expect(page.getByRole('button',{name:'Enregistrer les modifications',exact:true})).toHaveCount(0);
 await expect(page.locator('.v-summary-plate')).toHaveText('TEST-UI-01');
 await expect(page.locator('.v-summary-cover .photo-preview img')).toBeVisible();
 await page.getByRole('button',{name:'Agrandir Photo principale',exact:true}).click();
 await page.getByRole('button',{name:'Fermer l’aperçu',exact:true}).click();
 await expect(page.locator('.vehicle-summary')).toBeVisible();
 await page.screenshot({path:path.join(local,'vehicle-summary-desktop.png')});
 await page.getByRole('button',{name:/Modifier le fichier/}).click();
 await expect(page.locator('input[name=plate]')).toBeFocused();
 await page.getByLabel('Année',{exact:true}).selectOption('2024');
 await page.getByLabel('Nombre de places',{exact:true}).selectOption('5');
 await page.getByLabel('Nombre de portes',{exact:true}).selectOption('5');
 await page.getByRole('button',{name:'Enregistrer les modifications',exact:true}).click();
 await expect(page.locator('.vehicle-dialog')).not.toBeVisible();
 await open.click();
 const specs=page.locator('.v-summary-specs');
 await expect(specs.locator('div').filter({has:page.locator('dt',{hasText:/^Année$/})}).locator('dd')).toHaveText('2024');
 await expect(specs.locator('div').filter({has:page.locator('dt',{hasText:/^Places \(chauffeur inclus\)$/})}).locator('dd')).toHaveText('5');
 await expect(specs.locator('div').filter({has:page.locator('dt',{hasText:/^Portes$/})}).locator('dd')).toHaveText('5');
 await page.getByRole('button',{name:/Modifier le fichier/}).click();
 await expect(page.getByLabel('Année',{exact:true})).toHaveValue('2024');
 await page.getByLabel('Année',{exact:true}).selectOption('2020');
 page.once('dialog',d=>d.dismiss());
 await page.getByRole('button',{name:'Annuler',exact:true}).click();
 await expect(page.getByLabel('Année',{exact:true})).toHaveValue('2020');
 page.once('dialog',d=>d.accept());
 await page.getByRole('button',{name:'Annuler',exact:true}).click();
 await expect(page.locator('.vehicle-summary')).toBeVisible();
 await expect(specs.locator('div').filter({has:page.locator('dt',{hasText:/^Année$/})}).locator('dd')).toHaveText('2024');
 await page.setViewportSize({width:390,height:844});
 await page.screenshot({path:path.join(local,'vehicle-summary-mobile.png')});
 assert(await page.locator('.vehicle-dialog').evaluate(el=>el.scrollWidth<=el.clientWidth+1));
 await page.getByRole('button',{name:/Modifier le fichier/}).click();
 await page.getByLabel('Année',{exact:true}).selectOption('');
 await page.getByLabel('Nombre de places',{exact:true}).selectOption('');
 await page.getByLabel('Nombre de portes',{exact:true}).selectOption('');
 await page.getByRole('button',{name:'Enregistrer les modifications',exact:true}).click();
 await expect(page.locator('.vehicle-dialog')).not.toBeVisible();
 await open.click();
 for(const label of ['Année','Places \\(chauffeur inclus\\)','Portes']){
   await expect(specs.locator('div').filter({has:page.locator('dt').filter({hasText:new RegExp('^'+label+'$')})}).locator('dd')).toHaveText('Non renseigné');
 }
 await page.getByRole('button',{name:'Fermer',exact:true}).click();
 await page.getByLabel('Rechercher un véhicule', {exact:true}).fill('DEMO-1');
 await page.getByRole('button',{name:'Ouvrir DEMO-1',exact:true}).click();
 await expect(page.getByText('Pas encore de photo',{exact:true})).toBeVisible();
 await expect(page.locator('.v-summary-plate')).toHaveText('DEMO-1');
 await page.getByRole('button',{name:'Fermer',exact:true}).click();
 await page.getByRole('button',{name:'Ajouter un véhicule',exact:true}).click();
 await expect(page.locator('.vehicle-summary')).toHaveCount(0);
 await expect(page.locator('input[name=plate]')).toBeVisible();
 await expect(page.getByLabel('Année',{exact:true})).toHaveValue('');
 assert.equal(errors.length,0,errors.join('\n'));
 console.log('PASS: read-only summary, cover enlargement, edit gate, year/seats/doors save and clear, cancel confirmation, mobile, no-photo state and new-file editing.');
 }finally{await browser.close();}
})().catch(e=>{console.error(e);process.exit(1)});
