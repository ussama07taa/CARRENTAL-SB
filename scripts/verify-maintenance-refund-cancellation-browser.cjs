const {chromium}=require(process.env.PLAYWRIGHT_MODULE||'playwright');
const {expect}=require((process.env.PLAYWRIGHT_MODULE||'playwright')+'/test');
const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict');
const local=path.resolve(__dirname,'../.local');
const credentials=JSON.parse(fs.readFileSync(path.join(local,'demo-account.json'),'utf8'));
(async()=>{
 const browser=await chromium.launch({channel:'chrome',headless:true});
 try{
 const context=await browser.newContext({viewport:{width:1440,height:1000}});
 const page=await context.newPage();const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('http://localhost:3000/login');
 await page.getByLabel('Adresse e-mail',{exact:true}).fill(credentials.email);
 await page.getByLabel('Mot de passe',{exact:true}).fill(credentials.password);
 await page.getByRole('button',{name:'Se connecter',exact:true}).click();
 await expect(page).toHaveURL('http://localhost:3000/');
 await page.getByRole('link',{name:'Véhicules',exact:true}).click();
 const plate='TEST-REFUND-CANCEL-'+Date.now().toString().slice(-7);
 await page.getByRole('button',{name:'Ajouter un véhicule',exact:true}).click();
 await page.locator('input[name=plate]').fill(plate);
 await page.locator('select[name=make_choice]').selectOption('Dacia');
 await page.locator('select[name=model_choice]').selectOption('Logan');
 await page.getByRole('button',{name:'Créer le fichier',exact:true}).click();
 await page.getByRole('button',{name:'Fermer',exact:true}).click();
 await page.getByRole('link',{name:'Entretien & suivi',exact:true}).click();
 const add=page.getByRole('button',{name:'＋ Ajouter un entretien',exact:true});await expect(add).toBeEnabled();await add.click();
 const picker=page.locator('.mo-picker');
 await picker.getByLabel('Rechercher un véhicule',{exact:true}).fill(plate);
 await picker.getByRole('button',{name:'Choisir '+plate,exact:true}).click();
 await picker.getByRole('button',{name:'Continuer avec cette voiture',exact:true}).click();
 const form=page.locator('.gf-dialog');const op=form.locator('.gf-operation');

 await form.getByLabel('Montant (DH)',{exact:true}).fill('650');
 await form.getByLabel('Déjà payé / avance (DH)',{exact:true}).fill('650');
 await form.getByRole('button',{name:'Créer le dossier',exact:true}).click();
 await expect(form.locator('.gf-table tbody tr')).toHaveCount(1);
 await form.getByRole('button',{name:'↙ Remboursement reçu',exact:true}).click();
 await op.getByLabel('Montant reçu (DH)',{exact:true}).fill('500');
 await op.getByLabel('Motif du remboursement',{exact:true}).fill('Remboursement fictif, erreur de saisie volontaire');
 await op.getByText('Référence et justificatif',{exact:false}).click();
 await op.getByLabel('Justificatif du remboursement',{exact:true}).setInputFiles({name:'recu-fictif.pdf',mimeType:'application/pdf',buffer:Buffer.from('%PDF-1.4\n1 0 obj\n<< /Type /Catalog >>\nendobj\n%%EOF'.replaceAll('\\n','\n'))});
 await op.getByRole('checkbox').check();
 await op.getByRole('button',{name:'Confirmer la réception',exact:true}).click();
 await expect(op).toHaveCount(0);
 await expect(form.locator('.gf-cash-flow .gf-net-cash')).toContainText('150,00');
 await form.getByRole('button',{name:/Annuler le remboursement #/}).click();
 await op.getByRole('button',{name:'Confirmer l’annulation',exact:true}).click();
 await expect(op.getByLabel('Motif de l’annulation',{exact:true})).toHaveAttribute('aria-invalid','true');
 await expect(op.getByRole('checkbox')).toHaveAttribute('aria-invalid','true');
 await expect(op.locator('.gf-correction-preview')).toContainText('650,00');
 await expect(op.locator('.gf-correction-preview')).toContainText('0,00');
 await op.getByRole('button',{name:'Fermer sans annuler',exact:true}).click();
 await expect(op).toHaveCount(0);
 await expect(form.locator('.gf-cash-flow .gf-net-cash')).toContainText('150,00');
 await form.getByRole('button',{name:/Annuler le remboursement #/}).click();
 await op.getByLabel('Motif de l’annulation',{exact:true}).fill('500 DH saisis au lieu de 50 DH');
 await op.getByRole('checkbox').check();
 await op.locator('.gf-correction-preview').scrollIntoViewIfNeeded();
 await page.screenshot({path:path.join(local,'refund-cancellation-preview-desktop.png')});
 let cancelPosts=0;page.on('request',req=>{if(req.method()==='POST'&&/\/refunds\/\d+\/cancellations$/.test(req.url()))cancelPosts++});
 await op.getByRole('button',{name:'Confirmer l’annulation',exact:true}).evaluate(b=>{b.click();b.click()});
 await expect(op).toHaveCount(0);assert.equal(cancelPosts,1);
 await expect(form.locator('.gf-refund-cancelled')).toHaveCount(1);
 await expect(form.locator('.gf-refund-cancelled')).toContainText('500,00');
 await expect(form.locator('.gf-refund-cancelled')).toContainText('500 DH saisis au lieu de 50 DH');
 await expect(form.locator('.gf-refund-cancelled')).toContainText('Annulé · exclu des calculs');
 await expect(form.locator('.gf-refund-cancelled').getByRole('button',{name:/Annuler le remboursement #/})).toHaveCount(0);
 await expect(form.locator('.gf-cash-flow .gf-net-cash')).toContainText('650,00');
 const download=page.waitForEvent('download');await form.getByRole('button',{name:'Voir le justificatif',exact:true}).click();assert.ok((await download).suggestedFilename().endsWith('.pdf'));
 await form.getByRole('button',{name:'↙ Remboursement reçu',exact:true}).click();
 await op.getByLabel('Montant reçu (DH)',{exact:true}).fill('50');
 await op.getByLabel('Motif du remboursement',{exact:true}).fill('Montant réel reçu : 50 DH');
 await op.getByRole('checkbox').check();
 await op.getByRole('button',{name:'Confirmer la réception',exact:true}).click();
 await expect(op).toHaveCount(0);
 await expect(form.locator('.gf-refund-row')).toHaveCount(2);
 await expect(form.locator('.gf-refund-total')).toContainText('50,00');
 await expect(form.locator('.gf-cash-flow .gf-net-cash')).toContainText('600,00');
 await expect(form.locator('.gf-finance-balance')).toContainText('50,00');
 await page.setViewportSize({width:390,height:844});
 await form.locator('.gf-refunds').scrollIntoViewIfNeeded();
 await page.screenshot({path:path.join(local,'refund-cancellation-history-mobile.png')});
 assert.ok(await form.evaluate(el=>el.scrollWidth<=el.clientWidth+1),'Dialog fits mobile');
 await form.getByRole('button',{name:'Fermer',exact:true}).click();
 await page.getByLabel('Rechercher une voiture',{exact:true}).fill(plate);
 await page.getByRole('button',{name:/Paiements restants/}).click();
 await expect(page.locator('.mo-table tbody')).toContainText('50,00');
 await page.getByRole('button',{name:new RegExp('Enregistrer un paiement · '+plate)}).click();
 await expect(op).toBeVisible();
 await op.getByRole('button',{name:'Annuler',exact:true}).click();
 await expect(op).toHaveCount(0);
 await expect(form.locator('.gf-refund-cancelled')).toContainText('500 DH saisis au lieu de 50 DH');
 await expect(form.locator('.gf-refund-total')).toContainText('50,00');
 assert.equal(errors.length,0,errors.join(' | '));
 console.log('PASS '+plate+': paid650, wrong refund500 cancelled once, correct refund50 leaves net600/balance50; reason/confirmation required, close without cancellation, proof/history preserved, global balance, persistent mobile/desktop UI.');
 }finally{await browser.close();}
})().catch(e=>{console.error(String(e.stack||e).replaceAll(credentials.email,'[email]').replaceAll(credentials.password,'[password]'));process.exit(1)});
