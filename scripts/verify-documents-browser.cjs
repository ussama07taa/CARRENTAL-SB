  await page.getByRole('tab', { name: /Documents & photos/ }).click();
  await expect(page.getByRole('button', { name: 'Agrandir Permis · recto', exact: true })).toBeVisible();
  await page.locator('.document-card').first().scrollIntoViewIfNeeded();
  await page.screenshot({ path: path.join(local, 'documents-saved-desktop.png') });
  await page.getByRole('button', { name: 'Modifier le fichier', exact: true }).click();
  await page.getByLabel('Photo Identité · recto', { exact: true }).setInputFiles({ name: 'reprise-test.png', mimeType: 'image/png', buffer });
